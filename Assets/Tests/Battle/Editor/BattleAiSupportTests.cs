        private sealed class Port : BattleAiPort
        {
            public int Scene, Owner, Denied;
            public bool DenyFirst, Accept;
            public bool Back = true;
            public readonly List<string> Eligibility = new();
            public readonly List<int> BackQueries = new();

            public override int SceneFiveSpiritMode => Scene;

            public override int SceneFiveSpiritOwner => Owner;

            public override bool CanCast(int source, int skillId)
            {
                bool allowed = !DenyFirst || skillId != Denied;
                Eligibility.Add(skillId + ":" + (allowed ? 1 : 0));
                return allowed;
            }

            public override bool CanAttackBack(int source, int target)
            {
                BackQueries.Add(target);
                return Back;
            }

            public override long TryAttempt(BattleAiAttempt attempt) => Accept ? 7 : -1;
        }
