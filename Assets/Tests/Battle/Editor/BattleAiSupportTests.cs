        public static IEnumerable<TestCaseData> NativeCases()
        {
            for (int index = 0; index < NativeVectors.Length; index++)
                yield return new TestCaseData(NativeVectors[index]).SetName("OriginalAiSupportNative_" + index.ToString(CultureInfo.InvariantCulture));
        }

        private static int Number(string text) => int.Parse(text, CultureInfo.InvariantCulture);

        [TestCaseSource(nameof(NativeCases))]
        public void MatchesReleasedSupportSelector(string encoded)
        {
            string[] data = encoded.Split('|');
            if (data[0] is "L" or "J")
            {
                string leafCase = data[data[0] == "L" ? 4 : 3];
                var leafPort = new Port { Back = leafCase != "backBlocked" };
                var leafAi = new BattleAi(data[1] == "PAL3A", new BattleRandom(1, data[1]), leafPort);
                int[] indices = { 0, 1, 5, 6, 10 };
                int[] hpValues = { 100, 60, 30, 5, 5 };
                for (int index = 0; index < indices.Length; index++)
                {
                    int role = indices[index];
                    bool changed = role is 1 or 6;
                    leafAi.Roles[role] = new BattleAiRole
                    {
                        Valid = !changed || leafCase != "invalid",
                        Alive = !changed || leafCase != "deadFlag",
                        Hp = changed && leafCase == "zeroHp" ? 0 : hpValues[index],
                        Fled = changed && leafCase == "fled",
                        Fleeing = changed && leafCase == "fleeing"
                    };
                }
                if (data[0] == "L")
                {
                    Assert.That(unchecked((uint)leafAi.SelectRepeatTarget(0, data[2] == "2", data[3] == "1")).ToString(CultureInfo.InvariantCulture), Is.EqualTo(data[5]));
                    Assert.That(string.Join(",", leafPort.BackQueries), Is.EqualTo(data[6]));
                }
                else
                {
                    var leafCommand = new BattleAiCommand { Target = Number(data[2]) };
                    if (data[4].Length > 0)
                        leafCommand.TargetMask[6] = true;
                    Assert.That(leafAi.RepeatTargetsDead(leafCommand), Is.EqualTo(data[5] == "1"));
                }
                return;
            }
            if (data[0] == "U")
            {
                int[] nullOperations = data[3].Split(',').Select(Number).ToArray();
                var nullPort = new Port { DenyFirst = data[4].Length > 0, Denied = data[4].Length > 0 ? Number(data[4]) : 0 };
                var nullAi = new BattleAi(data[1] == "PAL3A", new BattleRandom(1, data[1]), nullPort);
                nullAi.Roles[0].Alive = true;
                nullAi.Roles[0].Hp = 40;
                nullAi.Roles[0].MaxHp = 200;
                BattleAiSkill[] nullRecords = Enumerable.Range(0, 4).Select(index => new BattleAiSkill
                {
                    Id = 9001 + index,
                    IsItem = data[2] == "Item",
                    IsMagic = data[2] == "Magic",
                    Type = data[2] == "Skill" ? 0 : data[2] == "Magic" ? 3 : 1,
                    Range = 1,
                    Power = new[] { 10, 40, 100, 400 }[index],
                    NullCureOperation = nullOperations[index]
                }).ToArray();
                nullAi.Roles[0].Skills = nullRecords;
                nullAi.Items = nullRecords;
                var nullKind = (BattleAiAttemptKind)Enum.Parse(typeof(BattleAiAttemptKind), "Cure" + data[2]);
                Assert.That(nullAi.SelectSupport(0, nullKind, false, 0, 0), Is.EqualTo(Number(data[5])));
                Assert.That(string.Join(",", nullPort.Eligibility), Is.EqualTo(data[6]));
                return;
            }
            if (data[0] == "N")
            {
                int normalSource = Number(data[2]);
                int normalTarget = Number(data[3]);
                string normalCase = data[4];
                var normalRandom = new BattleRandom(Number(data[5]), data[1]);
                var normalPort = new Port { Back = normalCase != "backBlocked" };
                var normalAi = new BattleAi(data[1] == "PAL3A", normalRandom, normalPort);
                foreach (int role in new[] { 0, 5 })
                {
                    normalAi.Roles[role].Valid = normalAi.Roles[role].Alive = true;
                    normalAi.Roles[role].Hp = normalAi.Roles[role].MaxHp = 100;
                    normalAi.Roles[role].Profile.Attack = true;
                }
                if (normalCase is "noAttack" or "chaosNoAttack" or "madNoAttack")
                    normalAi.Roles[normalSource].Profile.Attack = false;
                normalAi.Roles[normalSource].Chaos = normalCase == "chaosNoAttack";
                normalAi.Roles[normalSource].Madness = normalCase == "madNoAttack";
                if (normalCase == "targetDead")
                    normalAi.Roles[normalTarget].Alive = false;
                if (normalCase == "sourceDead")
                    normalAi.Roles[normalSource].Alive = false;
                normalAi.Roles[normalTarget].Fled = normalCase == "targetFled";
                normalAi.Roles[normalSource].Fled = normalCase == "sourceFled";
                bool normalResult = normalAi.CanNormalAttack(normalSource, normalTarget, normalCase == "invisible", normalCase is "wall" or "both", normalCase is "mirror" or "both", normalCase != "away");
                Assert.That(normalResult, Is.EqualTo(data[6] == "1"));
                Assert.That(normalRandom.State.ToString(CultureInfo.InvariantCulture), Is.EqualTo(data[7]));
                return;
            }
            if (data[0] == "C")
            {
                var conversionRandom = new BattleRandom(Number(data[3]), data[1]);
                var converter = new BattleAi(data[1] == "PAL3A", conversionRandom, new Port());
                Assert.That(converter.ConvertSingleAttackMagic(Number(data[2])), Is.EqualTo(Number(data[4])));
                Assert.That(conversionRandom.State.ToString(CultureInfo.InvariantCulture), Is.EqualTo(data[5]));
                return;
            }
            if (data[0] == "W")
            {
                var scenePort = new Port { Scene = Number(data[3]), Owner = Number(data[4]) };
                var sceneAi = new BattleAi(true, new BattleRandom(1, "PAL3A"), scenePort);
                sceneAi.Roles[Number(data[2])].Valid = true;
                Assert.That(sceneAi.IsSceneMagicForbidden(Number(data[2]), 9001, Number(data[5])), Is.EqualTo(data[6] == "1"));
                return;
            }
            bool five = data[0] == "F";
            string scenario = data[6];
            int source = five ? Number(data[2]) : 0;
            bool group = data[five ? 3 : 4] == "1";
            int weight = Number(data[5]);
            var port = new Port { Scene = five ? Number(data[4]) : 0, DenyFirst = scenario == "denied", Denied = five ? 265 : 9001 };
            var random = new BattleRandom(1, data[1]);
            var ai = new BattleAi(data[1] == "PAL3A", random, port);
            ai.Roles[source].Alive = ai.Roles[source].Valid = true;
            ai.Roles[source].Hp = 40;
            ai.Roles[source].MaxHp = 200;
            var records = new List<BattleAiSkill>();
            for (int index = 0; index < 4; index++)
            {
                int power = new[] { 10, 40, 100, 400 }[index];
                if (five)
                {
                    records.Add(new BattleAiSkill
                    {
                        Id = new[] { 9001, 265, 264, 9004 }[index],
                        Type = 2,
                        Range = 4,
                        Power = -power,
                        ElementMask = 1 << index,
                        Mastered = scenario != "unmastered" || index != 1
                    });
                    continue;
                }
                bool item = data[2] == "Item";
                bool attack = data[3] == "attack";
                int range = (attack ? 3 : 1) + (group ? 1 : 0);
                if (attack)
                    power = -power;
                if (scenario == "negative")
                    power = new[] { -20, 10, -40, 40 }[index];
                var operations = new int[32];
                if (data[3] == "revive" || scenario == "reviveFirst" && index == 0)
                    operations[24] = 2;
                else if (data[3] == "cure")
                    operations[0] = 2;
                records.Add(new BattleAiSkill
                {
                    Id = 9001 + index,
                    Type = item ? attack ? 2 : 1 : data[2] == "Skill" ? 0 : 3,
                    Range = scenario == "wrongRange" && index == 0 ? range == 1 ? 2 : 1 : range,
                    Power = power,
                    PowerMode = index == 0 ? scenario == "percentage" ? 1 : scenario == "full" ? 2 : 0 : 0,
                    Count = scenario == "zeroCount" && index == 0 ? 0 : 1,
                    IsItem = item,
                    IsMagic = data[2] == "Magic",
                    Mastered = scenario != "unmastered" || index != 0,
                    StateOperations = operations
                });
            }
            ai.Roles[source].Skills = records;
            ai.Items = records;
            int actual;
            if (five)
                actual = ai.SelectFiveSpiritMagic(source, group, weight);
            else
            {
                string name = char.ToUpperInvariant(data[3][0]) + data[3].Substring(1) + data[2];
                var kind = (BattleAiAttemptKind)Enum.Parse(typeof(BattleAiAttemptKind), name);
                actual = ai.SelectSupport(source, kind, group, weight);
            }
            Assert.That(actual, Is.EqualTo(Number(data[7])));
            Assert.That(string.Join(",", port.Eligibility), Is.EqualTo(data[8]));
            Assert.That(random.State, Is.EqualTo(1u));
        }

