        private static IEnumerable<TestCaseData> NativeCases()
        {
            foreach (string vector in NativeVectors)
                yield return new TestCaseData(vector);
        }

        [TestCaseSource(nameof(NativeCases))]
        public void DynamicFiveSpiritPowerMatchesPublishedImage(string vector)
        {
            string[] values = vector.Split(',');
            int Read(int index) => int.Parse(values[index], CultureInfo.InvariantCulture);
            int field = Read(0);
            var source = new BattleParticipant { Level = 20, Side = Read(1) == 0 ? BattleSide.Ally : BattleSide.Enemy, Slot = BattleSlot.Center };
            var target = new BattleParticipant { Side = source.Side == BattleSide.Ally ? BattleSide.Enemy : BattleSide.Ally };
            var random = new BattleRandom(Read(4));
            int power = new BattleEffectRules("PAL3A").MagicPower(Read(3), source, target, Read(2), random,
                field > 0 ? 1 << (field - 1) : 0, BattleEffectRules.GreaterElement(field));
            Assert.That(power, Is.EqualTo(Read(5)), vector);
            Assert.That(random.State, Is.EqualTo(uint.Parse(values[6], CultureInfo.InvariantCulture)), vector);
        }
